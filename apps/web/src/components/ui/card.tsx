import * as React from "react";

import { cn } from "@/lib/utils";

/**
 * Card — neutral surface for grouping related content.
 *
 * Honours the design rule: "Most cards should use border + minimal
 * or no shadow." Default card uses a border; `elevated` variant
 * adds a soft shadow for floating surfaces.
 *
 * Nested elements use a smaller radius than the parent.
 */
export const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement> & { elevated?: boolean }
>(({ className, elevated, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      "rounded-xl border border-border bg-card text-card-foreground",
      elevated && "shadow-sm",
      className,
    )}
    {...props}
  />
));
Card.displayName = "Card";

